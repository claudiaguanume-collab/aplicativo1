    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        String correo = txtUsuario.getText().trim();
String contrasena = new String(txtContrasena.getPassword());

if (correo.isEmpty() || contrasena.isEmpty()) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Por favor, ingresa el correo y la contraseña."
    );

    return;
}

String sql = "SELECT id_usuario, nombre FROM usuarios "
           + "WHERE correo = ? AND contrasena = ? AND estado = 'activo'";

try (
    java.sql.Connection cn = conexion.java.conectar();
    java.sql.PreparedStatement pst = cn.prepareStatement(sql)
) {

    pst.setString(1, correo);
    pst.setString(2, contrasena);

    java.sql.ResultSet rs = pst.executeQuery();

    if (rs.next()) {

        String nombre = rs.getString("nombre");

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Bienvenido, " + nombre + "."
        );

        julian inicio = new julian();
        inicio.setVisible(true);
        this.dispose();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Correo o contraseña incorrectos."
        );
    }

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Error al consultar la base de datos:\n" + e.getMessage()
    );
}
    }//GEN-LAST:event_btnIngresarActionPerformed

