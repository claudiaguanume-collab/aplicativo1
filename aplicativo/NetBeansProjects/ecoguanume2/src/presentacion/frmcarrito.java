    private void cargarCarrito() {

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tablaCarrito.getModel();

    modelo.setRowCount(0);

    double totalCompra = 0;

    for (int i = 0; i < Carrito.productos.size(); i++) {

        String producto = Carrito.productos.get(i);
        int cantidad = Carrito.cantidades.get(i);
        double precio = Carrito.precios.get(i);

        double totalProducto = cantidad * precio;

        modelo.addRow(new Object[]{
            producto,
            cantidad,
            precio,
            totalProducto
        });

        totalCompra += totalProducto;
    }

    lblTotalCompra.setText(
            "Total: $" + String.format("%.0f", totalCompra)
    );
}
     
